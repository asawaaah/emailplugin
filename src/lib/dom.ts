export type IconName = keyof typeof PATHS;

const SVG_NS = 'http://www.w3.org/2000/svg';

export function icon(name: IconName, size = 20): SVGSVGElement {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('class', 'icon');
  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', PATHS[name]);
  path.setAttribute('fill', 'currentColor');
  svg.append(path);
  return svg;
}

/** Bouton icône accessible (libellé lu par les lecteurs d'écran et en infobulle). */
export function iconButton(name: IconName, label: string, onClick: (event: MouseEvent) => void, extraClass = ''): HTMLButtonElement {
  const button = h('button', { type: 'button', class: `icon-button ${extraClass}`.trim(), title: label, 'aria-label': label }, icon(name));
  button.addEventListener('click', (event) => {
    event.stopPropagation();
    onClick(event);
  });
  return button;
}

/** Couleur d'avatar stable à partir d'une adresse. */
export function avatarHue(seed: string): number {
  let hash = 0;
  for (const char of seed) hash = (hash * 31 + char.charCodeAt(0)) >>> 0;
  return hash % 360;
}

/** Pastille avec l'initiale ; `color` impose la couleur (comptes), sinon elle découle de `seed`. */
export function avatar(name: string, seed: string, color?: string): HTMLElement {
  const letter = (name.trim()[0] ?? '?').toUpperCase();
  const el = h('span', { class: 'avatar', 'aria-hidden': 'true' }, letter);
  if (color && isHexColor(color)) {
    el.style.background = color;
    el.style.color = readableTextOn(color);
  } else {
    el.style.setProperty('--hue', String(avatarHue(seed)));
  }
  return el;
}
